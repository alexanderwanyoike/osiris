"""Build the Osiris live ISO.

    python3 iso/profile.py                      # generate the profile and build
    python3 iso/profile.py --generate-only      # just write build/iso-profile
    python3 iso/profile.py --out /var/tmp/osiris

Generates an archiso profile and hands it to mkarchiso. Must run as root -
mkarchiso mounts and chroots - and needs the `archiso` package.

Why archiso and not mkosi, which docs/ARCHITECTURE.md specifies: mkosi has no
ISO output format. Its Format= accepts directory, tar, cpio, disk, uki, esp,
oci, sysext, confext, portable, addon and none. It builds bootable disk images,
which are not bootable removable media. archiso is the tool for this job.

The profile is *generated*, not checked in. archiso requires profiledef.sh,
which is bash, and the project does not author bash. It contains no logic -
only variable assignments - so emitting it from Python is the same arrangement
as a compiler emitting assembly: the artefact is bash, the source is not.
"""
import argparse
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
# provision first so HERE, inserted after, takes precedence: both directories
# would otherwise offer a module named `packages` and the wrong one wins.
sys.path.insert(0, os.path.join(REPO, "provision"))
sys.path.insert(0, HERE)

import live_packages  # noqa: E402
from run import stream  # noqa: E402

ARCHISO_SHARE = "/usr/share/archiso/configs/releng"
INSTALL_DIR = "osiris"
ISO_LABEL = "OSIRIS"

# What gets copied into the live system so the installer can install from it.
PAYLOAD = ("provision", "apps", "branding", "shell/themes")
PAYLOAD_DIR = "/usr/share/osiris/source"


def profiledef(version: str) -> str:
    """The one bash file archiso requires. Assignments only, no logic.

    Upstream computes iso_label and iso_version with `date` command
    substitutions. Those are resolved here instead, so the generated file is a
    static description of one build rather than something that means a
    different thing depending on when it is read.
    """
    return (
        "#!/usr/bin/env bash\n"
        "# shellcheck disable=SC2034\n"
        "# Generated by iso/profile.py. Do not edit; edit that instead.\n"
        "\n"
        'iso_name="osiris"\n'
        f'iso_label="{ISO_LABEL}_{version.replace(".", "")}"\n'
        'iso_publisher="Osiris"\n'
        'iso_application="Osiris install medium"\n'
        f'iso_version="{version}"\n'
        f'install_dir="{INSTALL_DIR}"\n'
        "buildmodes=('iso')\n"
        # UEFI only: Osiris installs systemd-boot, so a BIOS machine would boot
        # the installer and then install a system it cannot boot.
        "bootmodes=('uefi.systemd-boot')\n"
        'arch="x86_64"\n'
        'pacman_conf="pacman.conf"\n'
        'airootfs_image_type="squashfs"\n'
        "airootfs_image_tool_options=('-comp' 'zstd' '-Xcompression-level' '18'"
        " '-b' '1M')\n"
        "file_permissions=(\n"
        '  ["/etc/shadow"]="0:0:400"\n'
        '  ["/root"]="0:0:750"\n'
        '  ["/usr/local/bin/osiris-installer"]="0:0:755"\n'
        ")\n"
    )


LOADER_CONF = f"""timeout 3
default 01-osiris.conf
"""

LOADER_ENTRY = f"""title    Osiris install medium
sort-key 01
linux    /%INSTALL_DIR%/boot/%ARCH%/vmlinuz-linux
initrd   /%INSTALL_DIR%/boot/%ARCH%/initramfs-linux.img
options  archisobasedir=%INSTALL_DIR% archisosearchuuid=%ARCHISO_UUID%
"""

# The archiso hooks locate and mount the squashfs the ISO is built around;
# without them the kernel boots and finds no root filesystem.
MKINITCPIO_CONF = """HOOKS=(base udev microcode modconf kms memdisk archiso \
block filesystems keyboard)
COMPRESSION="zstd"
"""

MKINITCPIO_PRESET = """# mkinitcpio preset for the 'linux' package on the Osiris ISO
PRESETS=('archiso')
ALL_kver='/boot/vmlinuz-linux'
archiso_config='/etc/mkinitcpio.conf.d/archiso.conf'
archiso_image="/boot/initramfs-linux.img"
"""

# xinit takes the client and then the server on argv, so a graphical session
# starts here without a shell or a display manager. Conflicts with getty@tty1
# so the two do not fight over the console.
INSTALLER_SERVICE = """[Unit]
Description=Osiris installer
After=systemd-user-sessions.service NetworkManager.service
Wants=NetworkManager.service
Conflicts=getty@tty1.service
After=getty@tty1.service

[Service]
Type=simple
ExecStart=/usr/bin/xinit /usr/local/bin/osiris-installer -- /usr/bin/X :0 vt1 -keeptty -nolisten tcp
Restart=on-failure
RestartSec=2
TTYPath=/dev/tty1
StandardInput=tty
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
"""

LAUNCHER = f"""#!/usr/bin/env python3
import runpy
import sys

sys.argv[0] = "osiris-installer"
runpy.run_path("{PAYLOAD_DIR}/apps/installer/main.py", run_name="__main__")
"""

# Root has no password on the live medium: there is nothing on it to protect,
# and locking it out of its own rescue console helps nobody.
SHADOW = """root::14871::::::
"""

# The `pacman-mirrorlist` package ships every mirror commented out, so a live
# system that installs it has no servers configured and pacstrap fails with
# "failed to synchronize all databases". archiso's own profile fixes this with
# a pacman hook that seds the file during the build; shipping the file is
# fewer moving parts and does not depend on sed at build time.
#
# Both of these are official Arch infrastructure. The geo mirror routes to the
# nearest tier-1; the second is a fallback for when it is unreachable.
MIRRORLIST = """# Osiris live medium. Only used to install from.
Server = https://geo.mirror.pkgbuild.com/$repo/os/$arch
Server = https://mirror.rackspace.com/archlinux/$repo/os/$arch
"""

# pacstrap verifies package signatures, which needs a populated keyring. The
# keyring lives on a tmpfs because the live root is a read-only squashfs.
GNUPG_MOUNT = """[Unit]
Description=Temporary /etc/pacman.d/gnupg directory

[Mount]
What=tmpfs
Where=/etc/pacman.d/gnupg
Type=tmpfs
Options=mode=0755,noswap
"""

PACMAN_INIT = """[Unit]
Description=Initialise the pacman keyring
Requires=etc-pacman.d-gnupg.mount
After=etc-pacman.d-gnupg.mount time-sync.target
BindsTo=etc-pacman.d-gnupg.mount

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/bin/pacman-key --init
ExecStart=/usr/bin/pacman-key --populate

[Install]
WantedBy=multi-user.target
"""


def write(path: str, text: str, mode: int | None = None) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)
    if mode is not None:
        os.chmod(path, mode)


def enable(root: str, unit: str, target: str = "multi-user.target") -> None:
    """Enable a unit the way archiso expects: a symlink, not systemctl.

    The profile is assembled on the build host, where systemctl would enable
    the unit for the build host rather than for the image.
    """
    wants = os.path.join(root, "etc/systemd/system", f"{target}.wants")
    os.makedirs(wants, exist_ok=True)
    link = os.path.join(wants, unit)
    if not os.path.islink(link):
        os.symlink(f"/usr/lib/systemd/system/{unit}", link)


def generate(out: str, version: str) -> str:
    """Write a complete archiso profile to `out`. Returns the path."""
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(out)

    write(os.path.join(out, "profiledef.sh"), profiledef(version), 0o755)
    write(os.path.join(out, "packages.x86_64"),
          "\n".join(live_packages.for_iso()) + "\n")

    # pacman.conf is configuration, not code, and upstream's is already correct
    # for a build host. Copying it keeps us tracking their mirror and signature
    # settings instead of maintaining a stale fork of them.
    source_pacman = os.path.join(ARCHISO_SHARE, "pacman.conf")
    if not os.path.exists(source_pacman):
        raise FileNotFoundError(
            f"{source_pacman} not found - install the 'archiso' package")
    shutil.copy(source_pacman, os.path.join(out, "pacman.conf"))

    write(os.path.join(out, "efiboot/loader/loader.conf"), LOADER_CONF)
    write(os.path.join(out, "efiboot/loader/entries/01-osiris.conf"),
          LOADER_ENTRY)

    root = os.path.join(out, "airootfs")
    write(os.path.join(root, "etc/mkinitcpio.conf.d/archiso.conf"),
          MKINITCPIO_CONF)
    write(os.path.join(root, "etc/mkinitcpio.d/linux.preset"),
          MKINITCPIO_PRESET)
    write(os.path.join(root, "etc/locale.conf"), "LANG=en_GB.UTF-8\n")
    write(os.path.join(root, "etc/pacman.d/mirrorlist"), MIRRORLIST)
    write(os.path.join(root, "etc/systemd/system/etc-pacman.d-gnupg.mount"),
          GNUPG_MOUNT)
    write(os.path.join(root, "etc/systemd/system/pacman-init.service"),
          PACMAN_INIT)

    # mkarchiso writes /etc/machine-id as "uninitialized" on purpose, which
    # turns on systemd's first-boot mechanism. systemd-firstboot then takes
    # tty1 and interactively asks for a timezone before the installer can
    # start. The installer asks for all of this itself, so the service is
    # masked outright, and /etc/localtime is shipped so nothing else is
    # tempted to ask either.
    os.symlink("/usr/share/zoneinfo/UTC", os.path.join(root, "etc/localtime"))
    mask = os.path.join(root, "etc/systemd/system/systemd-firstboot.service")
    os.symlink("/dev/null", mask)
    write(os.path.join(root, "etc/locale.gen"), "en_GB.UTF-8 UTF-8\n")
    write(os.path.join(root, "etc/hostname"), "osiris-live\n")
    write(os.path.join(root, "etc/shadow"), SHADOW, 0o400)
    write(os.path.join(root, "etc/systemd/system/osiris-installer.service"),
          INSTALLER_SERVICE)
    write(os.path.join(root, "usr/local/bin/osiris-installer"), LAUNCHER, 0o755)

    # The installer service lives in /etc, so its symlink has to point there
    # rather than at /usr/lib where packaged units live.
    wants = os.path.join(root, "etc/systemd/system/multi-user.target.wants")
    os.makedirs(wants, exist_ok=True)
    link = os.path.join(wants, "osiris-installer.service")
    if not os.path.islink(link):
        os.symlink("/etc/systemd/system/osiris-installer.service", link)
    enable(root, "NetworkManager.service")
    enable(root, "sshd.service")
    # Package signatures carry validity windows, so a wrong clock reads as an
    # invalid signature and pacstrap fails for a reason that looks like
    # anything but the clock.
    enable(root, "systemd-timesyncd.service", "sysinit.target")

    for unit in ("etc-pacman.d-gnupg.mount", "pacman-init.service"):
        wants_dir = os.path.join(root,
                                 "etc/systemd/system/multi-user.target.wants")
        os.makedirs(wants_dir, exist_ok=True)
        link = os.path.join(wants_dir, unit)
        if not os.path.islink(link):
            os.symlink(f"/etc/systemd/system/{unit}", link)

    payload = os.path.join(root, PAYLOAD_DIR.lstrip("/"))
    for relative in PAYLOAD:
        source = os.path.join(REPO, relative)
        if not os.path.isdir(source):
            raise FileNotFoundError(f"missing {source}")
        shutil.copytree(source, os.path.join(payload, relative),
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=os.path.join(REPO, "build"),
                        help="build directory (default: <repo>/build)")
    parser.add_argument("--version", default="0.1.0")
    parser.add_argument("--generate-only", action="store_true",
                        help="write the profile but do not build")
    args = parser.parse_args()

    profile = generate(os.path.join(args.out, "iso-profile"), args.version)
    print(f"profile: {profile}")
    if args.generate_only:
        return

    if os.geteuid() != 0:
        sys.exit("mkarchiso must run as root")
    if shutil.which("mkarchiso") is None:
        sys.exit("mkarchiso not found - install the 'archiso' package")

    work = os.path.join(args.out, "work")
    output = os.path.join(args.out, "out")
    os.makedirs(output, exist_ok=True)
    stream("mkarchiso", "-v", "-w", work, "-o", output, profile)

    images = sorted(f for f in os.listdir(output) if f.endswith(".iso"))
    for name in images:
        path = os.path.join(output, name)
        print(f"  {path}  ({os.path.getsize(path) / 1e9:.2f} GB)")
    print("ISO_BUILT")


if __name__ == "__main__":
    main()
