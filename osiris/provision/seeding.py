"""Files a person keeps in their home, which Osiris writes only once.

Setup runs again on every upgrade and the engine on every Theme switch, so
anything either writes into a home must not undo what the person changed
there (CONTEXT.md).
"""

from __future__ import annotations

#: The first lines of files Osiris wrote whole before it kept the person's.
#: Such a file was never the person's to keep: every switch rewrote it.
GENERATED = ("# Generated by the Osiris theme engine.", "# Osiris terminal defaults.")


def may_write(existing: str | None) -> bool:
    """Whether Osiris may write a file the person keeps, given what is there."""
    return existing is None or existing.startswith(GENERATED)


#: The login shell an Arch account gets when nobody chooses one.
_SYSTEM_SHELLS = ("/bin/bash", "/usr/bin/bash")


def moves_to_zsh(shell: str) -> bool:
    """Whether setup should make zsh this account's login shell."""
    return shell in _SYSTEM_SHELLS
