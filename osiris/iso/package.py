"""The `osiris` pacman package: what it contains and what it depends on.

Osiris reaches a machine the way every other piece of an Arch system does - as
a package, installed by pacman. archinstall installs it alongside the base
system and then runs `osiris-setup` from it (see ADR 0012). Later releases
arrive the same way, through `pacman -Syu`, rather than through a script of
ours.

The package is built by makepkg from a PKGBUILD generated here. A PKGBUILD is
bash, and the project authors no bash; like archiso's profiledef.sh, this one
is emitted from Python and holds assignments plus a single copy, so the
artefact is bash and the source is not.
"""

from __future__ import annotations

from collections.abc import Sequence

NAME = "osiris"
URL = "https://github.com/alexanderwanyoike/osiris"

#: Where the package puts the provisioning tree. The same path the live
#: medium uses for its copy, so every script resolves its siblings the same
#: way on both.
SOURCE_DIR = "/usr/share/osiris/source"

#: Directories of the repository that make up that tree.
PAYLOAD = ("osiris", "provision", "apps", "branding", "shell/themes")

SETUP = "/usr/bin/osiris-setup"

SETUP_LAUNCHER = f"""#!/usr/bin/env python3
import runpy
import sys

sys.argv[0] = "osiris-setup"
runpy.run_path("{SOURCE_DIR}/provision/setup.py", run_name="__main__")
"""

#: Packages that are in no official Arch repository, built from the pinned
#: PKGBUILDs in iso/bundled/<name>/ into Osiris's own repository alongside this
#: one, so the install can depend on them without the AUR.
#:
#: plank-reloaded is Plank, maintained: Plank 0.11.89, unreleased since 2019,
#: aborts on some GTK theme changes, and an Osiris theme switch is one.
BUNDLED: tuple[str, ...] = ("plank-reloaded",)

# What Osiris needs on top of the system archinstall builds. The kernel, the
# base system, the bootloader, microcode, graphics drivers, NetworkManager,
# PipeWire, LightDM with slick-greeter, Plymouth and Bluetooth are all
# archinstall's, chosen per machine, and are not repeated here.
DESKTOP = (
    "cinnamon", "cinnamon-translations", "nemo",
    "plank-reloaded", "rofi",
    "lightdm", "lightdm-slick-greeter",
    "xdg-desktop-portal-gtk", "xdg-user-dirs",
    "xed", "gnome-screenshot",
    "adw-gtk-theme", "papirus-icon-theme",
    "polkit", "upower", "brightnessctl",
)  # fmt: skip

# ghostty: GTK4-native and shaped through harfbuzz, so it is the only terminal
# in Arch's repositories with both font ligatures and transparency. chromium
# and code are the builds Arch packages; the Google and Microsoft ones are
# AUR-only, and a package in a repository cannot depend on the AUR.
APPLICATIONS = (
    "ghostty", "chromium", "code",
    "zsh", "zsh-completions", "fastfetch",
    "git", "openssh", "vim", "nano", "man-db", "which",
    "ttf-firacode-nerd", "ttf-jetbrains-mono-nerd",
    "noto-fonts", "noto-fonts-emoji",
    "xclip",
)  # fmt: skip

# What osiris-setup, Appearance and the theme switcher run on. Pillow and
# numpy render theme previews and wallpapers, including for themes made on the
# machine, so they are needed at runtime and not only at build time. pycairo is
# what the GTK apps draw with; python-gobject does not pull it in. glslang
# checks a wallpaper package's shader before the desktop compiles it, and
# mesa-utils' glxinfo says whether a GPU is there to draw it at all. grub
# supplies grub-mkfont and grub-mkconfig for the boot menu theme, and os-prober
# lets that menu list the other systems on a dual-boot machine. opencode is
# the Harness's Engine (ADR 0015); markdown-it-py parses its answers and
# GtkSourceView draws the code in them; the Osiris tool server speaks MCP with
# the official SDK.
RUNTIME = (
    "python", "python-gobject", "gtk4", "libadwaita",
    "python-pillow", "python-numpy", "python-cairo", "glslang", "mesa-utils",
    "dconf", "glib2",
    "grub", "os-prober", "plymouth", "mkinitcpio",
    "opencode", "python-markdown-it-py", "gtksourceview5", "python-mcp",
)  # fmt: skip


def depends() -> list[str]:
    return sorted({*DESKTOP, *APPLICATIONS, *RUNTIME})


def pkgbuild(version: str, release: int = 1, requires: Sequence[str] = ()) -> str:
    """The PKGBUILD, as text.

    `package()` copies a tree staged beside it into the package. Nothing is
    fetched or compiled: the tree is Python and assets, and the staging is
    done by the caller in Python, where it can be read and tested.
    """
    if "-" in version or not version:
        raise ValueError(f"not a valid pkgver: {version!r}")
    quoted = " ".join(f"'{name}'" for name in (requires or depends()))
    return (
        "# Generated by iso/repo.py from osiris/iso/package.py. Do not edit.\n"
        f"pkgname={NAME}\n"
        f"pkgver={version}\n"
        f"pkgrel={release}\n"
        "pkgdesc='Osiris: Cinnamon on Arch, themed as one system'\n"
        "arch=('any')\n"
        f"url='{URL}'\n"
        f"depends=({quoted})\n"
        "options=('!strip' '!debug')\n"
        "\n"
        "package() {\n"
        '  cp -a "$startdir/root/." "$pkgdir/"\n'
        "}\n"
    )
