"""Give Plank a dock theme in the palette's colours.

Plank reads a `dock.theme` ini file from `~/.local/share/plank/themes/<name>/`
and is pointed at one through a relocatable GSettings schema:

    net.launchpad.plank.dock.settings:/net/launchpad/plank/docks/dock1/ theme

Colours in that file are `R;;G;;B;;A`, each component 0-255 - not hex, and not
comma-separated.

As with the GTK theme, each palette gets its **own theme name** rather than one
theme whose contents are rewritten. Plank reads the file when the setting
changes; rewriting a file it is already pointed at leaves the dock as it was.
Changing the name makes it an ordinary theme change, which Plank handles.
"""
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import home  # noqa: E402

THEMES_DIR = os.path.join(home(), ".local", "share", "plank", "themes")
PREFIX = "Osiris-"
SCHEMA = "net.launchpad.plank.dock.settings"
PATH = "/net/launchpad/plank/docks/dock1/"

# How solid the dock sits over the wallpaper. Matched to the terminal's
# background-opacity so the two read as the same material.
FILL_ALPHA = 235
STROKE_ALPHA = 140


def _rgb(value: str) -> tuple[int, int, int]:
    v = value.lstrip("#")
    return tuple(int(v[i:i + 2], 16) for i in (0, 2, 4))


def _mix(a: str, b: str, t: float) -> tuple[int, int, int]:
    return tuple(round(x + (y - x) * t) for x, y in zip(_rgb(a), _rgb(b)))


def _colour(rgb: tuple[int, int, int], alpha: int) -> str:
    return ";;".join(str(c) for c in (*rgb, alpha))


def theme_name(theme: dict) -> str:
    return PREFIX + theme["name"]


def dock_theme(theme: dict) -> str:
    """The dock.theme file for a palette."""
    c = theme["colors"]
    # The same material as the top panel, very slightly lifted. An earlier
    # version went darker than the background on the theory that the dock
    # should recede; it read as a hole in the wallpaper instead. A dock floats
    # above the desktop, so it is lighter than what is behind it, not darker.
    top = _mix(c["surface"], c["foreground"], 0.05)
    bottom = c["surface"]
    inner = _colour(_mix(c["surface"], c["foreground"], 0.12), 70)
    return (
        "# Generated by Osiris. Edits are overwritten on the next theme change.\n"
        "[PlankDrawingTheme]\n"
        "TopRoundness=6\n"
        "BottomRoundness=6\n"
        "LineWidth=1\n"
        f"OuterStrokeColor={_colour(_rgb(c['border']), STROKE_ALPHA)}\n"
        f"FillStartColor={_colour(top, FILL_ALPHA)}\n"
        f"FillEndColor={_colour(_rgb(bottom), FILL_ALPHA)}\n"
        f"InnerStrokeColor={inner}\n"
        "\n"
        "[PlankDrawingDockTheme]\n"
        # Positive padding on every side: a negative TopPadding makes Plank
        # draw the icons overflowing the top edge, which looks like the dock
        # has come away from them.
        "HorizPadding=3\n"
        "TopPadding=2\n"
        "BottomPadding=2\n"
        "ItemPadding=3\n"
        "IndicatorSize=5\n"
        "UrgentBounceHeight=1.6666666666666667\n"
        "LaunchBounceHeight=0.625\n"
        "ClickTime=300\n"
        "UrgentBounceTime=600\n"
        "LaunchBounceTime=600\n"
        "ActiveTime=300\n"
        "SlideTime=300\n"
        "FadeTime=250\n"
        "HideTime=150\n"
        "GlowSize=30\n"
        "GlowTime=10000\n"
        "GlowPulseTime=2000\n"
    )


def build(theme: dict) -> str | None:
    """Write the dock theme for a palette. Returns its name, or None."""
    name = theme_name(theme)
    root = os.path.join(THEMES_DIR, name)
    try:
        os.makedirs(root, exist_ok=True)
        with open(os.path.join(root, "dock.theme"), "w") as fh:
            fh.write(dock_theme(theme))
    except OSError:
        return None

    for entry in os.listdir(THEMES_DIR):
        if entry.startswith(PREFIX) and entry != name:
            shutil.rmtree(os.path.join(THEMES_DIR, entry), ignore_errors=True)
    return name
