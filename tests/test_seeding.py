"""Files a person keeps in their home: Osiris writes each one once and then
leaves it to them."""

from __future__ import annotations

from osiris.provision.seeding import may_write, moves_to_zsh


def test_a_file_that_is_not_there_yet_is_seeded() -> None:
    assert may_write(None)


def test_a_file_the_person_has_is_left_alone() -> None:
    assert not may_write("font-size = 14\n")


def test_a_file_osiris_generated_before_it_kept_them_is_replaced() -> None:
    assert may_write("# Generated by the Osiris theme engine.\nfont-size = 11\n")
    assert may_write("# Osiris terminal defaults.\nfont-size = 11\n")


def test_an_account_still_on_the_system_shell_is_moved_to_zsh() -> None:
    assert moves_to_zsh("/bin/bash")
    assert moves_to_zsh("/usr/bin/bash")


def test_an_account_whose_shell_was_chosen_keeps_it() -> None:
    assert not moves_to_zsh("/usr/bin/fish")
    assert not moves_to_zsh("/usr/bin/zsh")
