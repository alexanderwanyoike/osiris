"""Install GRUB with the Osiris boot menu.

    python3 provision/grub.py [--repo PATH]

UEFI only, matching the rest of the install. Replaces systemd-boot, which has
no theme engine at all: it draws a text menu and offers no way to put anything
on screen before Plymouth starts. GRUB has a full graphical menu, and as a
second benefit os-prober can find other installed systems, which systemd-boot
never did.

The theme lives on the ESP at /boot/grub/themes/osiris. GRUB reads it from
there at boot, long before any filesystem but the ESP is mounted.
"""
import argparse
import os
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from run import capture, run  # noqa: E402

THEME_DIR = "/boot/grub/themes/osiris"
BOOTLOADER_ID = "Osiris"

# Fonts have to be GRUB's own .pf2 format. The family name set here is what
# theme.txt refers to; if the two disagree GRUB falls back to a bitmap font
# without saying so.
FONTS = (
    ("Osiris Sans", 18, "/usr/share/fonts/noto/NotoSans-Regular.ttf"),
    ("Osiris Sans", 28, "/usr/share/fonts/noto/NotoSans-Regular.ttf"),
    ("Osiris Sans", 14, "/usr/share/fonts/noto/NotoSans-Regular.ttf"),
    ("Osiris Mono", 16,
     "/usr/share/fonts/TTF/FiraCodeNerdFont-Regular.ttf"),
)

DEFAULTS = f"""# Generated by provision/grub.py. Edit that, not this.
GRUB_DEFAULT=0
GRUB_TIMEOUT=3
GRUB_TIMEOUT_STYLE=menu
GRUB_DISTRIBUTOR="Osiris"
GRUB_CMDLINE_LINUX_DEFAULT="quiet splash loglevel=3 rd.udev.log_level=3 vt.global_cursor_default=0"
GRUB_CMDLINE_LINUX=""

# The theme needs a graphical mode. `auto` takes the firmware's preferred
# resolution; keep_gfx keeps it through the handover so Plymouth does not have
# to bring the mode up again and flicker.
GRUB_GFXMODE=auto
GRUB_GFXPAYLOAD_LINUX=keep
GRUB_THEME="{THEME_DIR}/theme.txt"

GRUB_DISABLE_RECOVERY=true
# Other installed systems are worth finding. This is off by default in Arch's
# shipped config and is the main practical reason to prefer GRUB here.
GRUB_DISABLE_OS_PROBER=false
"""


def find_font(candidates: str) -> str | None:
    if os.path.exists(candidates):
        return candidates
    return None


def install_fonts() -> None:
    """Convert the UI fonts to .pf2 beside the theme."""
    made = set()
    for name, size, source in FONTS:
        if (name, size) in made:
            continue
        if find_font(source) is None:
            print(f"  missing {source}; GRUB will fall back for {name} {size}")
            continue
        target = os.path.join(THEME_DIR, f"{name.replace(' ', '-')}-{size}.pf2")
        run("grub-mkfont", "-n", name, "-s", str(size), "-o", target, source,
            check=False)
        made.add((name, size))
        print(f"  {os.path.basename(target)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default=os.path.dirname(
        os.path.dirname(os.path.abspath(__file__))))
    args = parser.parse_args()

    if os.geteuid() != 0:
        sys.exit("must run as root")

    source = os.path.join(args.repo, "branding", "grub")
    if not os.path.isdir(source):
        sys.exit(f"missing {source}; run branding/scripts/make-grub-theme.py")

    print("installing the boot menu theme")
    if os.path.isdir(THEME_DIR):
        shutil.rmtree(THEME_DIR)
    os.makedirs(THEME_DIR, exist_ok=True)
    for name in sorted(os.listdir(source)):
        if name.endswith((".png", ".txt")):
            shutil.copy(os.path.join(source, name),
                        os.path.join(THEME_DIR, name))
    print(f"  {THEME_DIR}")
    install_fonts()

    print("installing GRUB")
    with open("/etc/default/grub", "w") as fh:
        fh.write(DEFAULTS)
    # Twice, deliberately.
    #
    # The first writes /EFI/Osiris/grubx64.efi and a UEFI boot variable naming
    # it. That is the tidy result: the firmware menu shows "Osiris".
    #
    # The second writes the same loader to /EFI/BOOT/BOOTX64.EFI, the removable
    # media fallback that every UEFI firmware boots with no variable at all.
    # Without it the disk only boots on the machine the install ran on - the
    # boot variable lives in that machine's NVRAM, not on the disk. Move the
    # drive, clear CMOS, or install from a VM and boot elsewhere, and the
    # firmware reports no bootable device while the loader sits there intact.
    run("grub-install", "--target=x86_64-efi", "--efi-directory=/boot",
        f"--bootloader-id={BOOTLOADER_ID}", "--recheck")
    run("grub-install", "--target=x86_64-efi", "--efi-directory=/boot",
        "--removable", "--recheck")
    run("grub-mkconfig", "-o", "/boot/grub/grub.cfg")

    print("GRUB_CONFIGURED")


if __name__ == "__main__":
    main()
